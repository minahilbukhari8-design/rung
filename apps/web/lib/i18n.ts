const dict = { en, ur } as const;

export function t(locale: Locale, key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = dict[locale][key] ?? en[key];
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Pick the Urdu field when available in Urdu mode. */
export function pick(locale: Locale, en: string, ur?: string | null): string {
  return locale === 'ur' && ur ? ur : en;
}

